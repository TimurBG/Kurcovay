/**
 * @file DataProcessor.h
 * @brief Заголовочный файл класса DataProcessor для обработки данных
 * 
 * Содержит объявление класса DataProcessor, который предоставляет методы
 * для вычисления среднего значения и обработки переполнения.
 */

#pragma once

#include <vector>
#include <cstdint>

/**
 * @class DataProcessor
 * @brief Класс для обработки числовых данных
 * 
 * Предоставляет статические методы для вычисления среднего значения
 * вектора чисел и обработки переполнения при преобразовании типов.
 */
class DataProcessor {
public:
    /**
     * @brief Вычисляет среднее значение элементов вектора
     * @param vector Вектор значений
     * @return Среднее значение вектора или 0 если вектор пуст
     */
    static uint32_t calculateAverage(const std::vector<uint32_t>& vector);
    
    /**
     * @brief Обрабатывает переполнение при преобразовании типов
     * @param value Значение для преобразования
     * @return Значение, ограниченное диапазоном uint32_t
     * 
     * Если значение больше UINT32_MAX, возвращает UINT32_MAX.
     * Если значение меньше 0, возвращает 0.
     * Иначе возвращает значение, приведенное к uint32_t.
     */
    static uint32_t handleOverflow(uint64_t value);
};